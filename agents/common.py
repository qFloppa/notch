WAIT_INTERVAL_MS = 3000
WAIT_RETRIES = 120

# Transport faults, which are not verdicts. Matched on the exception *text*
# because genlayer_py wraps every provider failure in a single `GenLayerError`
# ("Request to ... failed: ..."), so the class alone cannot tell a dropped socket
# from a reverted call. Narrow list on purpose — anything unrecognised is re-raised
# rather than retried.
TRANSPORT_ERRORS = (
    "RemoteDisconnected", "Connection aborted", "ConnectionError",
    "Read timed out", "ReadTimeout", "Max retries exceeded",
    "Connection reset", "ProtocolError", "Temporary failure in name resolution",
)
TRANSPORT_ATTEMPTS = 5
TRANSPORT_BACKOFF_S = 5


def accounts():
    """The seller and buyer identities, from `.env`.

    Generated by `deploy/deploy.py` and pasted into `.env`, so both agent
    processes address the same two parties. Absent keys are a hard error rather
    than a silent fresh account, which would open a tab nobody else can see.
    """
    load_env()
    missing = [k for k in ("SELLER_KEY", "BUYER_KEY") if not os.environ.get(k)]
    if missing:
        raise SystemExit(
            f"missing {', '.join(missing)} in .env -- run deploy/deploy.py first")
    return (create_account(os.environ["SELLER_KEY"]),
            create_account(os.environ["BUYER_KEY"]))


def load_env(path=None):
    """Minimal `.env` reader. `KEY=value`, `#` comments, no quoting rules.

    ponytail: `python-dotenv` is already installed as a gltest dependency, but
    this is nine lines and keeps the demo runnable without importing the test
    harness. Swap it for `dotenv.load_dotenv` if the format ever grows.
    """
    p = pathlib.Path(path) if path else REPO / ".env"
    if not p.exists():
        return
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        os.environ.setdefault(k.strip(), v.strip())


def contract_address():
    load_env()
    addr = os.environ.get("NOTCH_ADDRESS")
    if not addr:
        raise SystemExit("missing NOTCH_ADDRESS in .env -- run deploy/deploy.py first")
    return addr


