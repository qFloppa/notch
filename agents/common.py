"""What the deploy script and both demo agents share.

Why `genlayer_py` directly and not `gltest`
-------------------------------------------
`gltest` is a pytest harness. Its config layer only initialises under pytest —
`get_accounts()` outside it dies with `KeyError: None`
(`gltest_cli/config/types.py:150`) — and on studionet it mints **ten fresh
random accounts per process** (`gltest_cli/config/user.py:40`), so a seller
process and a buyer process could never share an identity through it. The demo
needs two stable keys across two scripts, so it reads them from `.env` and
drives `genlayer_py` itself.

Two consequences worth knowing, both good:

- **No ASCII shim.** The integration suite patches `encode_hex` because
  `factory.deploy()` ends in a schema fetch that passes the contract *source*
  to a function doing `.encode("ascii")`, and this contract holds 71 non-ASCII
  characters. Nothing here fetches a schema: the source is deployed as **bytes**
  and calls are made by name, so that whole failure mode is out of scope.
- **No Windows loader shim** either. That one is direct-mode only.
"""
