def failure_detail(receipt) -> str:
    """Why a write failed, from the fields that actually carry it.

    Never grep a receipt for short strings: the payload is hex-encoded contract
    source and matches any digit sequence you look for. A grep for `429` once
    produced a phantom rate-limit diagnosis in this project. Read the named
    fields.
    """
    lr = (receipt.get("consensus_data") or {}).get("leader_receipt") or [{}]
    lr = lr[0] if lr else {}
    parts = [f"execution_result={lr.get('execution_result')}",
             f"status={receipt.get('status_name')}",
             f"result={receipt.get('result_name')}"]
    stderr = (lr.get("genvm_result") or {}).get("stderr")
    if stderr:
        parts.append(f"stderr={str(stderr)[:300]}")
    return "  ".join(parts)


def succeeded(receipt) -> bool:
    """`execution_result == SUCCESS`, and nothing weaker.

    ACCEPTED and FINALIZED are lifecycle states, not success: a reverted call
    finalizes too, with every validator agreeing about the error, so a vote
    count alone looks healthy. Same check `gltest.assertions` makes, inlined so
    the agents do not import the test harness.
    """
    lr = (receipt.get("consensus_data") or {}).get("leader_receipt") or []
    return bool(lr) and lr[0].get("execution_result") == "SUCCESS"


class Notch:
    """A client bound to one contract and one signer, with waiting built in."""

    def __init__(self, client, address, account, label=""):
        self.client = client
        self.address = address
        self.account = account
        self.label = label

    def read(self, fn, *args):
        """A view call, retried on transport failure.

        Same reason as `write`: a dropped connection says nothing about the
        contract, and a view is idempotent so retrying it is free.
        """
        return self._transport_retry(
            lambda: self.client.read_contract(
                address=self.address, function_name=fn, args=list(args)),
            f"read {fn}")

    @staticmethod
    def _transport_retry(fn, label, attempts=TRANSPORT_ATTEMPTS):
        """Retry a call that failed *before* the network had an opinion.

        studionet drops connections occasionally — a 25-notch run hit
        `RemoteDisconnected('Remote end closed connection without response')`
        partway through, and a 200-notch run is 40 minutes of exposure to that.
        The endpoint was healthy seconds later, so the only thing that failed was
        the transport.

        Deliberately narrow. This retries the HTTP round trip, never a
        transaction the network actually judged: `GenLayerError` from a *receipt*
        (a revert, a failed verdict) is a real answer and is not retried, because
        re-sending a write the chain already accepted would bill a second notch.
        The wrapper is only applied where the call is idempotent — reads, and the
        `write_contract` submit step, which returns a hash rather than a result.
        """
        last = None
        for i in range(attempts):
            try:
                return fn()
            except Exception as e:
                text = f"{type(e).__name__}: {e}"
                if not any(m in text for m in TRANSPORT_ERRORS):
                    raise
                last = e
                wait_s = TRANSPORT_BACKOFF_S * (i + 1)
                print(f"    transport error on {label} "
                      f"(attempt {i+1}/{attempts}), retrying in {wait_s}s")
                print(f"      {text[:160]}")
                time.sleep(wait_s)
        raise SystemExit(f"{label} failed after {attempts} transport attempts: "
                         f"{last}")

    def write(self, fn, *args, value=0, quiet=False, finalized=False):
        """Send, wait, raise on anything that is not SUCCESS.

        Raises rather than returning a flag: every call site here treats a failed
        write as fatal, and a demo that printed a warning and carried on would
        report a verdict on a dispute that was never filed.

        `finalized=True` waits for FINALIZED instead of ACCEPTED. Needed by
        exactly one caller, `withdraw`, and for a measured reason: a value
        transfer's effect on `eth_getBalance` is **not visible at ACCEPTED**.
        Checked immediately after an accepted `withdraw`, the recipient's balance
        still reads its pre-transfer value and the contract still holds the bond;
        re-read minutes later, the contract is drained and the recipient is whole.
        So a demo that waited only for ACCEPTED would print `delta 0` and imply
        the payout failed. Costs ~70s.
        """
        t0 = time.time()
        status = (TransactionStatus.FINALIZED if finalized
                  else TransactionStatus.ACCEPTED)
        # Finalization is slower than acceptance by an order of magnitude, so it
        # gets a longer leash rather than the same one.
        interval = 5000 if finalized else WAIT_INTERVAL_MS
        retries = 90 if finalized else WAIT_RETRIES
        # Submit and wait are retried separately, and only for transport faults.
        # Once a hash exists the transaction is the network's business, so the
        # wait is resumed rather than the send repeated.
        tx = self._transport_retry(
            lambda: self.client.write_contract(
                address=self.address, function_name=fn, args=list(args),
                account=self.account, value=value),
            f"submit {fn}")
        receipt = self._transport_retry(
            lambda: self.client.wait_for_transaction_receipt(
                transaction_hash=tx, status=status,
                interval=interval, retries=retries),
            f"await {fn}")
        if not succeeded(receipt):
            raise SystemExit(
                f"{self.label}{fn} FAILED after {time.time()-t0:.0f}s\n"
                f"  {failure_detail(receipt)}")
        if not quiet:
            print(f"  {fn:16s} ok  {time.time()-t0:5.1f}s"
                  f"{'  (finalized)' if finalized else ''}")
        return receipt


def statement_hash(tab_id: str, cycle: int, notch_ids, legs) -> str:
    """Rebuild `close()`'s preimage and hash it, off-chain.

    A second implementation of `contracts/notch.py:370-373` **on purpose** —
    that is the whole point of a verifiable statement, and a shared helper would
    prove only that one function agrees with itself. `tests/direct/test_hash.py`
    pins the two together, so a drift in either is a red suite rather than a
    demo that quietly stops checking anything.

    The contract sorts `notches` and emits `legs` in sorted-key order with no
    spaces; both are reproduced here exactly, including `separators`.
    """
    import hashlib

    payload = json.dumps(
        {"tab": tab_id, "cycle": cycle, "notches": sorted(notch_ids),
         "legs": legs},
        sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def usdc(atto: int) -> str:
    """Atto to a readable USDC figure. Integer arithmetic only, no floats."""
    atto = int(atto)
    whole, frac = divmod(atto, 10**18)
    return f"{whole}.{frac:018d}".rstrip("0").rstrip(".") or "0"
